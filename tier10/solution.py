"""Tier 10 solution: Shor's discrete logarithm with one recycled control qubit.

The checker runs this file from the repo root. Keep these imports; they work
there.

Method
------
g has order q = 41 modulo p = 83 and A = g^a. Let U_g|x> = |g x mod p> and
U_A|x> = |A x mod p> on the subgroup generated by g. They commute and share
eigenvectors |u_s>, s = 0..q-1, with

    U_g |u_s> = e^(2 pi i s / q) |u_s>,     U_A |u_s> = e^(2 pi i s a / q) |u_s>

because U_A = U_g^a. The state |1> is an equal mix of all |u_s>. Phase
estimation of U_g on |1> returns s for a random s and leaves the work register
(almost) in |u_s>. Phase estimation of U_A on the same register then returns
s*a mod q. Dividing the two gives a = (s a) * s^-1 mod q. This is the
two-dimensional period finding of f(x1, x2) = g^x1 A^x2 mod p, read one
dimension after the other.

Circuit
-------
* Both phase estimations are done one bit at a time with a single control
  qubit that is measured, reset and reused (semiclassical QFT), t = 7 bits
  each. 2^7 = 128 > 2 q, so rounding y q / 2^t gives s when the estimate is
  one of the two closest values.
* Controlled multiplication by a constant b is a permutation of the 41
  subgroup elements, written as a product of swaps of two basis states. Each
  swap is CX gates plus one multi-controlled X. This costs O(q) gates per
  multiplication: a toy construction that only works at these sizes.
* The constants g^(2^j) and A^(2^j) mod p come from repeated squaring.
* The very first round acts on the known state |1>, where "multiply by b" is
  just "write b": a few CX gates.
"""
import math
from collections import Counter

from qiskit import ClassicalRegister, QuantumCircuit, QuantumRegister, transpile
from qiskit.synthesis import synth_mcx_1_clean_kg24, synth_mcx_2_clean_kg24
from qiskit_aer import AerSimulator

from common import load_locked, keystream, xor_bytes

BASIS = ["rz", "sx", "x", "cx"]
TIER = 10
SHOTS = 40
PHASE_BITS = 7
# Clean ancillas for the multi-controlled X gates, and the matching synthesis.
N_ANCILLAS = 2
MCX_SYNTHESIS = {1: synth_mcx_1_clean_kg24, 2: synth_mcx_2_clean_kg24}[N_ANCILLAS]


# --------------------------------------------------------------------------
# Controlled modular multiplication as a permutation circuit.
# --------------------------------------------------------------------------

def mcx_cost(n_controls):
    """CX count of a multi-controlled X with clean ancillas (measured)."""
    return {0: 0, 1: 1, 2: 6}.get(n_controls, 6 * n_controls - 6)


def swap_gate(u, v, n_bits, free):
    """Cheapest gates that swap basis states u and v of the work register.

    Returns (cost, cx_list, pattern, pivot): apply the CX gates, flip `pivot`
    when the work bits match `pattern`, undo the CX gates.

    The CX gates make u and v differ in the pivot bit only. A control on
    another bit can be left out when that only adds swaps between `free`
    states, the bit patterns the work register can never hold.
    """
    best = None
    difference = u ^ v
    for pivot in range(n_bits):
        if not (difference >> pivot) & 1:
            continue
        others = [q for q in range(n_bits) if q != pivot and (difference >> q) & 1]
        fixed, moved = (u, v) if not (u >> pivot) & 1 else (v, u)
        dropped, deltas = [], [0]
        for q in reversed(range(n_bits)):
            if q == pivot:
                continue
            extra = [delta | (1 << q) for delta in deltas]
            if all((fixed ^ delta) in free and (moved ^ delta) in free for delta in extra):
                dropped.append(q)
                deltas += extra
        pattern = {q: (fixed >> q) & 1 for q in range(n_bits) if q != pivot and q not in dropped}
        cost = 2 * len(others) + mcx_cost(1 + len(pattern))
        if best is None or cost < best[0]:
            best = (cost, [(pivot, q) for q in others], pattern, pivot)
    return best


def swap_sequence(permutation, n_bits, free):
    """Write a permutation {x: image} as a list of swap gates, in time order.

    Swapping two values that sit in the same cycle splits that cycle in two,
    so repeating this ends with the identity. The cheapest swap is taken each
    time.
    """
    remaining = dict(permutation)
    cache = {}
    gates = []
    while True:
        best = None
        seen = set()
        for start in remaining:
            if start in seen or remaining[start] == start:
                continue
            cycle, x = [], start
            while x not in seen:
                seen.add(x)
                cycle.append(x)
                x = remaining[x]
            for i, u in enumerate(cycle):
                for v in cycle[i + 1:]:
                    if (u, v) not in cache:
                        cache[u, v] = swap_gate(u, v, n_bits, free)
                    if best is None or cache[u, v][0] < best[0][0]:
                        best = (cache[u, v], u, v)
        if best is None:
            return gates
        gate, u, v = best
        gates.append(gate[1:])
        remaining[u], remaining[v] = remaining[v], remaining[u]


def apply_classically(gates, x):
    """Run the swap gates on one basis state with plain bits (for testing)."""
    for cx_list, pattern, pivot in gates:
        for control, target in cx_list:
            x ^= ((x >> control) & 1) << target
        if all((x >> q) & 1 == value for q, value in pattern.items()):
            x ^= 1 << pivot
        for control, target in reversed(cx_list):
            x ^= ((x >> control) & 1) << target
    return x


def subgroup(modulus, order):
    """The elements x with x^order = 1 mod p, found with Euler's criterion.

    These are exactly the powers of g. Testing membership takes one modular
    exponentiation per element and reveals no discrete logarithm.
    """
    return [x for x in range(1, modulus) if pow(x, order, modulus) == 1]


def controlled_multiplier(b, modulus, n_bits, valid):
    """Circuit for |c>|x> -> |c>|b^c x mod modulus>, for every x in `valid`.

    Qubit 0 is the control, qubits 1..n_bits the work register (bit j has
    value 2^j), and the last N_ANCILLAS qubits are clean ancillas.

    The work register starts at 1 and is only ever multiplied by powers of g,
    so it always holds an element of the subgroup generated by g. Every other
    bit pattern is "free": the circuit may do anything to it.
    """
    free = set(range(2 ** n_bits)) - set(valid)
    permutation = {x: (b * x) % modulus for x in valid}
    gates = swap_sequence(permutation, n_bits, free)
    for x, image in permutation.items():
        assert apply_classically(gates, x) == image

    circuit = QuantumCircuit(1 + n_bits + N_ANCILLAS, name=f"x{b} mod {modulus}")
    work = lambda q: 1 + q
    ancillas = list(range(1 + n_bits, 1 + n_bits + N_ANCILLAS))
    for cx_list, pattern, pivot in gates:
        zeros = [work(q) for q, value in pattern.items() if value == 0]
        for control, target in cx_list:
            circuit.cx(work(control), work(target))
        if zeros:
            circuit.x(zeros)
        controls = [0] + [work(q) for q in pattern]
        if len(controls) <= 2:
            circuit.mcx(controls, work(pivot))
        else:
            circuit.compose(MCX_SYNTHESIS(len(controls)), controls + [work(pivot)] + ancillas, inplace=True)
        if zeros:
            circuit.x(zeros)
        for control, target in reversed(cx_list):
            circuit.cx(work(control), work(target))
    return circuit


# --------------------------------------------------------------------------
# Two phase estimations with one control qubit.
# --------------------------------------------------------------------------

def dlog_circuit(g, big_a, modulus, order, t=PHASE_BITS, optimization_level=2):
    """Estimate the phases of U_g and then U_A on the same work register."""
    n_bits = modulus.bit_length()
    valid = subgroup(modulus, order)
    control = QuantumRegister(1, "ctrl")
    work = QuantumRegister(n_bits, "work")
    ancilla = QuantumRegister(N_ANCILLAS, "anc")
    registers = [ClassicalRegister(t, "s_g"), ClassicalRegister(t, "s_A")]
    circuit = QuantumCircuit(control, work, ancilla, *registers)
    circuit.x(work[0])  # work register = |1>

    blocks = {}
    first = True
    for base, bits in zip((g, big_a), registers):
        for i in range(t):
            b = pow(base, 2 ** (t - 1 - i), modulus)
            if not first:
                circuit.reset(control)
            circuit.h(control)
            if first:
                # The work register is exactly |1>: multiplying by b writes b.
                for q in range(n_bits):
                    if ((1 ^ b) >> q) & 1:
                        circuit.cx(control[0], work[q])
                first = False
            else:
                if b not in blocks:
                    blocks[b] = transpile(
                        controlled_multiplier(b, modulus, n_bits, valid),
                        basis_gates=BASIS, optimization_level=optimization_level, seed_transpiler=1,
                    )
                circuit.compose(blocks[b], inplace=True)
            # Semiclassical inverse QFT: undo the phase from the bits already read.
            for earlier in range(i):
                with circuit.if_test((bits[earlier], 1)):
                    circuit.p(-2 * math.pi / 2 ** (i - earlier + 1), control)
            circuit.h(control)
            circuit.measure(control, bits[i])
    return circuit


def run_dlog(parameters, shots=SHOTS, seed=10):
    """Run the circuit on Aer. Returns counts {(y_g, y_A): shots}."""
    circuit = dlog_circuit(parameters["g"], parameters["A"], parameters["p"], parameters["order"])
    backend = AerSimulator(method="statevector", seed_simulator=seed)
    counts = backend.run(circuit, shots=shots).result().get_counts()
    result = Counter()
    for bits, n in counts.items():
        y_a, y_g = bits.split()  # the register added last is printed first
        result[int(y_g, 2), int(y_a, 2)] += n
    return result


# --------------------------------------------------------------------------
# Classical post-processing.
# --------------------------------------------------------------------------

def exponent_votes(counts, order, t=PHASE_BITS):
    """Turn each shot (y_g, y_A) into a candidate exponent. Returns a Counter."""
    votes = Counter()
    for (y_g, y_a), n in counts.items():
        s = round(y_g * order / 2 ** t) % order       # y_g / 2^t ~ s / q
        s_a = round(y_a * order / 2 ** t) % order     # y_A / 2^t ~ s a / q
        if s == 0:
            continue  # s = 0 carries no information about a
        votes[(s_a * pow(s, -1, order)) % order] += n
    return votes


def recover_exponent(parameters):
    """Return (a, votes): the exponent with the most votes, checked once."""
    counts = run_dlog(parameters)
    votes = exponent_votes(counts, parameters["order"])
    a = votes.most_common(1)[0][0]
    if pow(parameters["g"], a, parameters["p"]) != parameters["A"]:
        raise RuntimeError("the most frequent exponent does not reproduce A")
    return a, votes


def build_circuit():
    """Return your main circuit. Used for diagrams only, never for scoring."""
    parameters = load_locked(TIER)["public_parameters"]
    return dlog_circuit(parameters["g"], parameters["A"], parameters["p"], parameters["order"])


def solve():
    """Run your circuit on Aer and return the decrypted line as a string."""
    locked = load_locked(TIER)
    parameters = locked["public_parameters"]
    ciphertext = bytes.fromhex(locked["ciphertext_hex"])
    a, _ = recover_exponent(parameters)
    secret = pow(parameters["B"], a, parameters["p"])
    key_bits = format(secret, f"0{parameters['key_width_bits']}b")
    return xor_bytes(ciphertext, keystream(key_bits, len(ciphertext))).decode("utf-8")
